"""M5 capture report: what the replayer sent and what capture stored. Every number in
distill/RESULTS.md comes from here.

    docker compose --profile distill run --rm distill-tools python -m distill.report
    (or on the host, with CAPTURE_PARQUET_DIR pointing at a copy of the capture volume)
"""

import asyncio
import json
import os
import uuid
from collections import Counter, defaultdict
from decimal import Decimal
from pathlib import Path
from typing import Any

import pyarrow.parquet as pq
from sqlalchemy import select

from distill.datasets import TASKS, read
from distill.replay import KEY_ID_FILE, SENT_FILE, TASK_NAMES
from distill.report_distill import render_distillation
from gateway.capture.fingerprint import system_fingerprint
from gateway.capture.pii import scrub
from gateway.core.config import Settings
from gateway.core.schemas import ChatMessage
from gateway.db.models import CaptureEventRow
from gateway.db.repositories import SqlDistillAudit
from gateway.db.session import make_engine, make_sessionmaker

OUT = Path("distill/results")
PARQUET = Path(os.environ.get("CAPTURE_PARQUET_DIR", "data/capture"))


def task_fingerprints() -> dict[str | None, str]:
    """system fingerprint -> task name (noise traffic has no system prompt: None)."""
    out: dict[str | None, str] = {}
    for task in TASK_NAMES:
        if not (TASKS / f"{task}.jsonl").exists():
            continue
        first = read(task)[0]
        fp = system_fingerprint([ChatMessage.model_validate(m) for m in first.messages])
        out[fp] = task
    return out


async def capture_rows(settings: Settings) -> list[CaptureEventRow]:
    """Events from the replay key only (tests and load tests write other rows)."""
    key_id = uuid.UUID(KEY_ID_FILE.read_text(encoding="utf-8").strip())
    engine = make_engine(settings.database_url)
    try:
        async with engine.connect() as conn:
            query = select(CaptureEventRow).where(CaptureEventRow.key_id == key_id)
            return list(await conn.execute(query))  # type: ignore[arg-type]
    finally:
        await engine.dispose()


def parquet_stats() -> dict[str, int]:
    files = sorted(PARQUET.rglob("*.parquet"))
    ids: list[str] = []
    for f in files:
        ids.extend(pq.read_table(f, columns=["event_id"]).column("event_id").to_pylist())
    return {"files": len(files), "rows": len(ids), "distinct_events": len(set(ids))}


def sent_stats() -> dict[str, dict[str, int]]:
    out: dict[str, Counter[str]] = defaultdict(Counter)
    if SENT_FILE.exists():
        for line in SENT_FILE.read_text("utf-8").splitlines():
            row = json.loads(line)
            out[row["task"]][str(row["status"])] += 1
    return {task: dict(c) for task, c in out.items()}


def summarize(rows: list[CaptureEventRow], names: dict[str | None, str]) -> dict[str, Any]:
    by_task: dict[str, dict[str, Any]] = {}
    for r in rows:
        task = names.get(r.system_fingerprint, "other")
        t = by_task.setdefault(
            task,
            {
                "events": 0,
                "simulated": 0,
                "content_captured": 0,
                "ok": 0,
                "prompt_tokens": 0,
                "completion_tokens": 0,
                "list_price_cost_usd": Decimal(0),
                "pii_redactions": 0,
                "served_alias": Counter(),
            },
        )
        t["events"] += 1
        t["simulated"] += r.simulated
        t["content_captured"] += r.content_captured
        t["ok"] += r.status == "ok"
        t["prompt_tokens"] += r.prompt_tokens
        t["completion_tokens"] += r.completion_tokens
        t["list_price_cost_usd"] += r.cost_usd
        t["pii_redactions"] += r.pii_redactions
        t["served_alias"][r.served_alias] += 1
    for t in by_task.values():
        t["list_price_cost_usd"] = format(t["list_price_cost_usd"], "f")
        t["served_alias"] = dict(t["served_alias"])
    return by_task


def scrubber_hits() -> dict[str, dict[str, int]]:
    """How often the PII scrubber changes the *public-dataset* prompts (which contain no real
    PII): every hit there is a false positive that would alter training data."""
    out: dict[str, dict[str, int]] = {}
    for task in TASK_NAMES:
        if not (TASKS / f"{task}.jsonl").exists():
            continue
        examples = read(task)
        hits = sum(
            scrub(e.messages[-1]["content"]).text != e.messages[-1]["content"] for e in examples
        )
        out[task] = {"prompts": len(examples), "changed": hits}
    return out


def render(
    data: dict[str, Any], load: dict[str, Any] | None, distill: list[str] | None = None
) -> str:
    lines = [
        "# Distillation results",
        "",
        "_Generated by `docker compose --profile distill run --rm distill-tools python -m "
        "distill.report`. **All traffic below is simulated** (public datasets replayed through "
        "the gateway by `distill/replay.py`)._",
        "",
        "## M5: capture",
        "",
        "### What was captured",
        "",
        "| Task | Events | Simulated | With content | OK | Prompt tok | Completion tok "
        "| List-price cost | PII redactions | Served by |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for task, t in sorted(data["by_task"].items()):
        served = ", ".join(f"{k} ({v})" for k, v in t["served_alias"].items())
        lines.append(
            f"| {task} | {t['events']} | {t['simulated']} | {t['content_captured']} | {t['ok']} "
            f"| {t['prompt_tokens']} | {t['completion_tokens']} | ${t['list_price_cost_usd']} "
            f"| {t['pii_redactions']} | {served} |"
        )
    p = data["parquet"]
    lines += [
        "",
        f"- **Parquet:** {p['files']} files, {p['rows']} rows, {p['distinct_events']} distinct "
        "events (rows minus distinct = duplicates from at-least-once replays; readers dedupe).",
        "- **List-price cost** = tokens times `models.yaml` prices. Actual spend is **$0**: "
        "Groq's free tier serves the strong model, and noise traffic replays recorded answers.",
        "- **Replayer outcomes** (HTTP status per request, from `data/replay/sent.jsonl`): "
        + "; ".join(f"{task}: {codes}" for task, codes in sorted(data["sent"].items())),
    ]
    hits = data["scrubber_false_positives"]
    lines += [
        "",
        "### PII scrubber on public data (false positives)",
        "",
        "The datasets contain no real personal data, so any prompt the scrubber changes is a "
        "false positive that would alter training data. Measured over every prepared prompt "
        "(`data/tasks/*.jsonl`), not just the replayed ones:",
        "",
        "| Task | Prompts | Changed by scrubber |",
        "|---|---|---|",
        *(f"| {t} | {h['prompts']} | {h['changed']} |" for t, h in sorted(hits.items())),
        "",
        "The hits are long digit runs: a WikiSQL table column of 10-digit numbers, a log "
        "timestamp, coordinate lists. M6's dataset builder must drop examples the scrubber "
        "changed, or a redacted WikiSQL table would no longer match its gold query.",
    ]
    if load is not None:
        lines += ["", "### Overhead on the hot path", "", load["text"]]
    if distill:
        lines += ["", *distill]
    return "\n".join(lines) + "\n"


def load_overhead() -> dict[str, Any] | None:
    """The capture section of loadtest/RESULTS.md, if the k6 comparison has been run."""
    results = Path("loadtest/RESULTS.md").read_text(encoding="utf-8")
    marker = "## Distillation capture: overhead off vs on"
    if marker not in results:
        return None
    section = results.split(marker, 1)[1].split("\n## ", 1)[0]
    body = "\n".join(section.strip().splitlines()[1:]).strip()
    return {"text": f"From `loadtest/RESULTS.md` (`loadtest/run.py --capture-only`):\n\n{body}"}


def main() -> None:
    settings = Settings()
    rows = asyncio.run(capture_rows(settings))
    data = {
        "by_task": summarize(rows, task_fingerprints()),
        "parquet": parquet_stats(),
        "sent": sent_stats(),
        "scrubber_false_positives": scrubber_hits(),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "m5_capture.json").write_text(json.dumps(data, indent=2), encoding="utf-8")
    sessions = make_sessionmaker(make_engine(settings.database_url))
    events = asyncio.run(SqlDistillAudit(sessions).recent(50))
    distill = render_distillation(events, "banking77-intent")
    Path("distill/RESULTS.md").write_text(render(data, load_overhead(), distill), encoding="utf-8")
    print(json.dumps(data, indent=2))


if __name__ == "__main__":
    main()
