"""Render loadtest/RESULTS.md from results/results.json (+ hand-written loadtest/analysis.md)."""

from pathlib import Path
from typing import Any

ANALYSIS = Path(__file__).with_name("analysis.md")

HEADER = """# Load test results

_Generated by `uv run python loadtest/run.py`. Raw k6 summaries: `loadtest/results/`._

- Run: {started}, {duration} per step, constant arrival rate (k6).
- Machine: {cpus} logical CPUs; Docker VM: {docker}. Everything (k6, nginx, gateway replicas,
  Redis, Postgres primary + replica, mock LLM) shares this one machine.
- Upstream: a mock OpenAI-compatible server with a fixed **100 ms** latency (4 workers), so the
  numbers measure the gateway, not a provider. Real provider keys are blanked in the load-test
  overlay.
- Every request takes the full path: API-key auth (cached), RPM + TPM token buckets, spend
  reservation + settlement, circuit breaker, upstream call, async request log.
  `temperature: 0.7` with unique prompts, so there are no cache hits.
- Each gateway replica is one uvicorn process (one event loop, at most one CPU core).
- **Gateway overhead** = the gateway's own `Server-Timing` header (total time minus time spent
  waiting on the upstream), measured inside the replica.
"""


def _ms(trend: dict[str, float], key: str) -> str:
    return f"{trend[key]:.1f}"


def _cpu(step: dict[str, Any]) -> str:
    top = sorted(step.get("cpu_percent", {}).items(), key=lambda kv: -kv[1])[:6]
    return ", ".join(f"{name} {pct:.0f}%" for name, pct in top)


def _step_row(replicas: int, step: dict[str, Any]) -> str:
    lat, ovh = step["latency_ms"], step["gateway_overhead_ms"]
    status = "✅" if step["sustained"] else "❌ saturated"
    cells = [
        str(replicas),
        str(step["target_rps"]),
        str(step["achieved_rps"]),
        f"{step['success_rate'] * 100:.2f}%",
        f"{_ms(lat, 'med')} / {_ms(lat, 'p(99)')}",
        f"{_ms(ovh, 'med')} / {_ms(ovh, 'p(95)')} / {_ms(ovh, 'p(99)')}",
        status,
    ]
    return "| " + " | ".join(cells) + " |"


def _scaling(sweeps: list[dict[str, Any]]) -> list[str]:
    lines = [
        "## Scaling: max sustained throughput",
        "",
        "| Replicas | Max sustained RPS | Speedup vs 1 replica |",
        "|---|---|---|",
    ]

    def best_of(sweep: dict[str, Any]) -> float:
        return max((float(s["target_rps"]) for s in sweep["steps"] if s["sustained"]), default=0)

    base = best_of(sweeps[0]) or 1
    for sweep in sweeps:
        best = best_of(sweep)
        speedup = best / base
        lines.append(f"| {sweep['replicas']} | **{best:.0f}** | {speedup:.2f}x |")
    lines += [
        "",
        "Max sustained = the highest *offered* rate where achieved ≥ 95% of it, ≥ 99% of requests "
        "succeeded and p99 latency ≤ 1 s. The ladder stops at the first saturated step. "
        "(k6's achieved rate reads slightly above the offered rate because it divides by active "
        "time; it's shown per step but not used as the headline.)",
    ]
    return lines


def _overhead(sweeps: list[dict[str, Any]]) -> list[str]:
    lines = [
        "## Gateway overhead at the lowest load step",
        "",
        "| Replicas | RPS | Overhead p50 | p95 | p99 | End-to-end p50 (incl. 100 ms mock) |",
        "|---|---|---|---|---|---|",
    ]
    for sweep in sweeps:
        first = sweep["steps"][0]
        o = first["gateway_overhead_ms"]
        lines.append(
            f"| {sweep['replicas']} | {first['target_rps']} | {_ms(o, 'med')} ms "
            f"| {_ms(o, 'p(95)')} ms | {_ms(o, 'p(99)')} ms "
            f"| {_ms(first['latency_ms'], 'med')} ms |"
        )
    return lines


def _extras(data: dict[str, Any]) -> list[str]:
    lines: list[str] = []
    if "streaming" in data:
        s = data["streaming"]
        o = s["gateway_overhead_ms"]
        lines += [
            "",
            f"## Streaming (1 replica, {s['target_rps']} RPS)",
            "",
            f"Gateway overhead until the first content chunk is forwarded: p50 {_ms(o, 'med')} ms, "
            f"p99 {_ms(o, 'p(99)')} ms (mock: 50 ms TTFT, 20 chunks). "
            f"Success {s['success_rate'] * 100:.2f}%.",
        ]
    if "failover" in data:
        f = data["failover"]
        lines += [
            "",
            "## Losing a replica under load",
            "",
            f"3 replicas at {f['target_rps']} RPS for 30 s; one replica is stopped "
            f"(`docker stop`: graceful SIGTERM) 10 s in. Success rate: "
            f"**{f['success_rate'] * 100:.2f}%**, p99 latency {_ms(f['latency_ms'], 'p(99)')} ms.",
        ]
    return lines


def _overload(data: dict[str, Any]) -> list[str]:
    if "overload" not in data:
        return []
    o = data["overload"]
    lines = [
        "",
        f"## Past saturation: load shedding off vs on ({o['replicas']} replica)",
        "",
        f"Same arrival rates, one replica (saturates at ~80 RPS). **On** = at most {o['cap']} "
        "requests in flight per replica; the rest get an immediate `503` + `Retry-After: 1`. "
        "Goodput = successful responses per second. Latency is for successful requests only, so "
        "fast 503s don't flatter it. Dropped = arrivals k6 couldn't even send (all its virtual "
        "users were stuck waiting).",
        "",
        "| Offered RPS | Shedding | Goodput | Shed | OK latency p50 / p99 (ms) | Dropped |",
        "|---|---|---|---|---|---|",
    ]
    off, on = o["runs"]["off"], o["runs"]["on"]
    for a, b in zip(off, on, strict=True):
        for label, s in (("off", a), ("on", b)):
            ok = s["ok_latency_ms"]
            lines.append(
                f"| {s['target_rps']} | {label} | {s['goodput_rps']} | "
                f"{s['shed_rate'] * 100:.1f}% | {_ms(ok, 'med')} / {_ms(ok, 'p(99)')} | "
                f"{s['dropped_iterations']} |"
            )
    study = o.get("cap_study", [])
    if study:
        lines += [
            "",
            "### Choosing the cap",
            "",
            "Shedding on, one replica. Goodput (OK latency p99) at each offered rate:",
            "",
            "| Cap | "
            + " | ".join(f"{r} RPS" for r in sorted({s["target_rps"] for s in study}))
            + " |",
            "|---|" + "---|" * len({s["target_rps"] for s in study}),
        ]
        for cap in sorted({s["cap"] for s in study}):
            cells = [
                f"{s['goodput_rps']} ({_ms(s['ok_latency_ms'], 'p(99)')} ms)"
                for s in sorted(study, key=lambda s: s["target_rps"])
                if s["cap"] == cap
            ]
            mark = " (chosen)" if cap == o["cap"] else ""
            lines.append(f"| {cap}{mark} | " + " | ".join(cells) + " |")
    return lines


def render(data: dict[str, Any]) -> str:
    sweeps = data["sweeps"]
    lines = [
        HEADER.format(
            started=data["started"],
            duration=data["duration"],
            cpus=data["machine"]["cpus"],
            docker=data["machine"]["docker"],
        ),
        *_scaling(sweeps),
        "",
        *_overhead(sweeps),
        "",
        "## Every step",
        "",
        "| Replicas | Offered RPS | Achieved RPS | Success | Latency p50 / p99 (ms) "
        "| Overhead p50 / p95 / p99 (ms) | |",
        "|---|---|---|---|---|---|---|",
    ]
    for sweep in sweeps:
        lines += [_step_row(sweep["replicas"], step) for step in sweep["steps"]]
    lines += ["", "## CPU at the saturated step (`docker stats`; 100% = one core)", ""]
    for sweep in sweeps:
        last = sweep["steps"][-1]
        lines.append(
            f"- **{sweep['replicas']} replica(s)** @ {last['target_rps']} RPS: {_cpu(last)}"
        )
    lines += _extras(data)
    lines += _overload(data)
    if ANALYSIS.exists():
        lines += ["", ANALYSIS.read_text(encoding="utf-8").strip()]
    return "\n".join(lines) + "\n"
